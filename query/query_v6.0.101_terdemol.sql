-- ----------------------------------------------------------------------------
-- Limpieza de duplicados heredados (solo si NO estan referenciados):
--   'NUEVA YORK' -> duplicado de 'NEW YORK'
--   'SUCRE' (Bolivia) -> redundante con 'CHUQUISACA' (Sucre es la capital)
-- ----------------------------------------------------------------------------
DELETE d FROM departamento d
JOIN pais p ON p.idpais = d.idpais
WHERE p.idcompania = 1
  AND ( (p.nombre = 'ESTADOS UNIDOS' AND d.nombre = 'NUEVA YORK')
     OR (p.nombre = 'BOLIVIA'        AND d.nombre = 'SUCRE') )
  AND NOT EXISTS (SELECT 1 FROM personacliente x WHERE x.iddepartamento = d.iddepartamento)
  AND NOT EXISTS (SELECT 1 FROM contactocliente x WHERE x.iddepartamento = d.iddepartamento)
  AND NOT EXISTS (SELECT 1 FROM ciudad x WHERE x.iddepartamento = d.iddepartamento);
